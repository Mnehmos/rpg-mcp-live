export function ruinedGatehouseWorldContextCommand(): EngineWorldContextCommand {
  return {
    kind: "world_context",
    title: "Ruined gatehouse",
    description: "A collapsed gatehouse frames a locked door, a broken bridge mechanism, and the last safe route clue.",
    features: ["collapsed bridge", "gatehouse-threshold"],
    exits: [],
    objects: {
      upsert: RUINED_GATEHOUSE_OBJECTS.map((entry) => ({
        ...entry,
        definition: {
          ...entry.definition,
          tags: [...entry.definition.tags],
          affordances: [...entry.definition.affordances],
          prerequisites: entry.definition.prerequisites.map((prerequisite) => ({ ...prerequisite, requiredTags: [...prerequisite.requiredTags] })),
          effectInteractions: entry.definition.effectInteractions.map((interaction) => ({ ...interaction })),
          criticalPolicy: { ...entry.definition.criticalPolicy },
        },
      })),
    },
  };
}
