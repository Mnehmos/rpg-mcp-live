const policy = (
  kind: EngineWorldObjectInput["definition"]["criticalPolicy"]["kind"],
  options: Partial<Omit<EngineWorldObjectInput["definition"]["criticalPolicy"], "kind">> = {},
): EngineWorldObjectInput["definition"]["criticalPolicy"] => ({
  kind,
  canDestroy: true,
  canLose: true,
  canSell: true,
  canConsume: true,
  canHide: true,
  ...options,
});

const object = (
  id: string,
  sourceRef: string,
  name: string,
  description: string,
  material: EngineWorldObjectInput["definition"]["material"],
  tags: string[],
  affordances: EngineWorldObjectInput["definition"]["affordances"],
  state: EngineWorldObjectInput["state"],
  criticalPolicy: EngineWorldObjectInput["definition"]["criticalPolicy"],
  effectInteractions: EngineWorldObjectInput["definition"]["effectInteractions"] = [],
): EngineWorldObjectInput => ({
  id,
  definition: {
    key: id,
    sourceRef,
    name,
    description,
    material,
    tags,
    affordances,
    prerequisites: [],
    effectInteractions,
    weight: 1,
    criticalPolicy,
  },
  state,
  locationRef: "ruined-gatehouse",
});

